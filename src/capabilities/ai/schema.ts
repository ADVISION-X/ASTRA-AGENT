import { z } from "zod";

import {
  VisualMissionActionPlanOutputSchema,
  VisualMissionActionPlanRequestInputSchema,
} from "../../types/visual-mission-action-plan.js";

const AiTaskTypeSchema = z.literal("visual_mission_judgment");
const AiPromptContractIdSchema = z.literal("visual-mission-judge-v1");
const AiOutputSchemaRefSchema = z.literal("ai.visual_mission_judgment.v1");

const AiAbilityInputRefSchema = z.object({
  id: z.string().min(1),
  kind: z.string().min(1),
  summary: z.string().min(1),
  filePath: z.string().min(1).optional(),
}).strict();

const AiRuntimeProofSchema = z.object({
  proofId: z.string().min(1),
  abilityGroupId: z.literal("ai"),
  childCapabilityId: z.literal("visual-mission-judge-once"),
  missionId: z.string().min(1),
  runId: z.string().min(1),
  sessionId: z.string().min(1),
  roundId: z.string().min(1).nullable(),
  videoVisitId: z.string().min(1).nullable(),
  requestHash: z.string().min(1),
  inputPayloadHash: z.string().min(1),
  promptContractHash: z.string().min(1),
  modelConfigHash: z.string().min(1),
  runtimeCallId: z.string().min(1).nullable(),
  startedAt: z.string().datetime(),
  endedAt: z.string().datetime(),
  durationMs: z.number().nonnegative(),
  status: z.enum(["success", "failed", "review_required"]),
  reason: z.string().min(1),
  failureReason: z.string().min(1).nullable(),
  reviewRequiredReason: z.string().min(1).nullable(),
  inputRefs: z.array(z.string().min(1)).default([]),
  outputRefs: z.array(z.string().min(1)).default([]),
  evidenceRefs: z.array(z.string().min(1)).default([]),
  rawOutputRef: z.string().min(1).nullable(),
  rawOutputHash: z.string().min(1).nullable(),
  timeoutMs: z.number().nonnegative().nullable(),
  attemptIndex: z.number().int().nonnegative(),
  retryCount: z.number().int().nonnegative(),
  circuitBreakerState: z.enum(["closed", "open", "half_open", "not_applicable"]),
  gatewayDurationMs: z.number().nonnegative().nullable(),
  actionLogRefs: z.array(z.string().min(1)).default([]),
  nextAbilityGroup: z.string().min(1).nullable(),
  nextChildAbility: z.string().min(1).nullable(),
  schemaIssueCount: z.number().int().nonnegative(),
  boundaryViolationCount: z.number().int().nonnegative(),
  qualityDecisionReason: z.string().min(1).nullable(),
  dataQualityFlags: z.array(z.string().min(1)).default([]),
  schemaDecision: z.string().min(1),
  qualityDecision: z.string().min(1),
  outputBoundaryDecision: z.string().min(1),
}).strict();

const AiAbilityInputSchema = z.object({
  abilityGroupId: z.literal("ai"),
  missionId: z.string().min(1),
  runId: z.string().min(1),
  sessionId: z.string().min(1),
  roundId: z.string().min(1).nullable().optional().default(null),
  videoVisitId: z.string().min(1).nullable().optional().default(null),
  capabilityCallId: z.string().min(1),
  nerveBusEnvelopeId: z.string().min(1),
  requestedBy: z.literal("orchestration"),
  transportedBy: z.literal("nerve-bus"),
  taskType: AiTaskTypeSchema,
  promptContractId: AiPromptContractIdSchema,
  expectedOutputSchema: AiOutputSchemaRefSchema,
  inputRefs: z.array(AiAbilityInputRefSchema).min(1),
  userRequirementRef: z.string().min(1).nullable().optional().default(null),
  userRequirementText: z.string().min(1),
  platformId: z.string().min(1),
  platformProfileRef: z.string().min(1).nullable().optional().default(null),
  originalScreenshotRef: z.string().min(1),
  coordinateGridScreenshotRef: z.string().min(1),
  gridSpecRef: z.string().min(1),
  visualMissionInputRef: z.string().min(1).nullable().optional().default(null),
  systemManualRef: z.string().min(1),
  muscleMemoryCatalogVersion: z.string().min(1),
  continuityBundleRef: z.string().min(1).nullable().optional().default(null),
  input: VisualMissionActionPlanRequestInputSchema,
}).passthrough();

const AiAbilityResultSchema = z.object({
  abilityGroupId: z.literal("ai"),
  childCapabilityId: z.literal("visual-mission-judge-once"),
  status: z.enum(["success", "failed", "review_required"]),
  taskType: AiTaskTypeSchema,
  missionId: z.string().min(1),
  runId: z.string().min(1),
  modelProvider: z.literal("online"),
  modelName: z.string().min(1),
  modelRole: z.literal("vision"),
  runtime: z.string().min(1),
  implementationStatus: z.string().min(1),
  output: VisualMissionActionPlanOutputSchema.nullable(),
  rawOutputRef: z.string().min(1).nullable(),
  rawOutputHash: z.string().min(1).nullable(),
  schemaValidationStatus: z.enum(["valid", "invalid", "not_applicable"]),
  confidence: z.number().min(0).max(1).nullable(),
  failureReason: z.string().min(1).nullable(),
  reviewRequiredReason: z.string().min(1).nullable().optional().default(null),
  durationMs: z.number().nonnegative(),
  runtimeProof: AiRuntimeProofSchema,
  promptContractId: AiPromptContractIdSchema,
  promptContractVersion: z.string().min(1),
  promptCatalogVersion: z.string().min(1),
  promptVersion: z.string().min(1),
  schemaVersion: z.string().min(1),
  createdAt: z.string().datetime(),
}).strict();

export {
  AiAbilityInputRefSchema,
  AiAbilityInputSchema,
  AiAbilityResultSchema,
  AiOutputSchemaRefSchema,
  AiPromptContractIdSchema,
  AiRuntimeProofSchema,
  AiTaskTypeSchema,
};
