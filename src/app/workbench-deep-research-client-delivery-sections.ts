import type { DeepResearchReport } from "./workbench-deep-research-client-contracts.js";
import { deepResearchClientSharedRuntime } from "./workbench-deep-research-client-shared.js";

const {
  escapeText,
  formatDateTime,
  renderListSection,
  renderMetaRow,
  setResearchHtml,
} = deepResearchClientSharedRuntime;

const renderPrimaryBusinessReport = (report: DeepResearchReport): void => {
  const primaryReport = report.primaryBusinessReport;
  if (!primaryReport || !primaryReport.htmlExport) {
    setResearchHtml("[data-deep-research-primary-business-report]", `
      <div class="research-section-head">
        <div>
          <p class="research-kicker">Primary Business Report</p>
          <h2>HTML report not generated</h2>
        </div>
      </div>
      <p class="muted">The AI HTML Report Publisher runs after final adjudication and persists business-report.html when available.</p>`);
    return;
  }
  const sourceLabel = primaryReport.sourceKind === "html_artifact"
    ? "HTML artifact"
    : primaryReport.sourceKind === "raw_html_text"
      ? "Raw HTML text"
      : "Unknown source";
  setResearchHtml("[data-deep-research-primary-business-report]", `
    <div class="research-section-head">
      <div>
        <p class="research-kicker">Primary Business Report</p>
        <h2>AI-generated HTML decision report</h2>
      </div>
    </div>
    ${renderMetaRow([
      "Status HTML generated",
      `Generated by ${primaryReport.generatedBy}`,
      `Source ${sourceLabel}`,
      primaryReport.htmlExport.fileSizeBytes ? `${primaryReport.htmlExport.fileSizeBytes} bytes` : null,
      primaryReport.generatedAt ? formatDateTime(primaryReport.generatedAt) : null,
    ])}
    <div class="research-delivery-strip">
      <button class="btn secondary" type="button" data-deep-research-open-export="business-report.html">Open HTML Report</button>
      <button class="btn secondary" type="button" data-deep-research-export="business-report.html">Download HTML Report</button>
    </div>
    <div class="research-summary-grid">
      ${renderListSection("Delivery Metadata", [
        `Kind: ${primaryReport.htmlExport.exportKind}`,
        `File: ${primaryReport.htmlExport.fileName}`,
        `Hash: ${primaryReport.htmlExport.fileHash}`,
      ])}
      ${renderListSection("Generated At", primaryReport.generatedAt ? [formatDateTime(primaryReport.generatedAt)] : [], { emptyText: "Not generated yet." })}
    </div>`);
};

const renderBusinessDeckActions = (report: DeepResearchReport): string => {
  const deck = report.businessDeck;
  if (!deck) {
    return "";
  }
  const pptxKind = deck.pptxExport?.exportKind ?? "";
  return [
    deck.pptxExport
      ? `<button class="btn secondary" type="button" data-deep-research-open-export="${escapeText(pptxKind)}">Open PPT</button>`
      : "",
    deck.pptxExport
      ? `<button class="btn secondary" type="button" data-deep-research-export="${escapeText(pptxKind)}">Download PPT</button>`
      : "",
    deck.outlineExport
      ? '<button class="btn secondary" type="button" data-deep-research-open-export="business-deck-outline.json">Open Deck Outline</button>'
      : "",
  ].filter(Boolean).join("");
};

const renderBusinessDeckMeta = (deck: NonNullable<DeepResearchReport["businessDeck"]>): string => {
  const pptxStatus = deck.status === "ai_generated"
    ? "Available"
    : deck.status === "local_fallback"
      ? "Fallback"
      : "Missing";
  return renderMetaRow([
    `Status ${pptxStatus}`,
    deck.pptxExport ? `Generated by ${deck.generatedBy}` : null,
    deck.audience ? `audience ${deck.audience}` : null,
    deck.slideCount ? `${deck.slideCount} slides` : null,
    deck.pptxExport?.fileSizeBytes ? `${deck.pptxExport.fileSizeBytes} bytes` : null,
    deck.generatedAt ? formatDateTime(deck.generatedAt) : null,
  ]);
};

const renderOptionalPresentationDeck = (report: DeepResearchReport): void => {
  if (!report.businessDeck) {
    setResearchHtml("[data-deep-research-business-deck]", `
      <div class="research-section-head">
        <div>
          <p class="research-kicker">Optional Presentation Deck</p>
          <h2>Presentation deck not generated</h2>
        </div>
      </div>
      <p class="muted">PPT is optional and does not block the primary business HTML report.</p>`);
    return;
  }
  const actionButtons = renderBusinessDeckActions(report);
  const deckStatusMessage = report.businessDeck.pptxExport
    ? ""
    : '<p class="muted">Optional PPT not generated.</p>';
  setResearchHtml("[data-deep-research-business-deck]", `
    <div class="research-section-head">
      <div>
        <p class="research-kicker">Optional Presentation Deck</p>
        <h2>${escapeText(report.businessDeck.deckTitle || "Presentation deck")}</h2>
      </div>
    </div>
    ${report.businessDeck.deckSubtitle ? `<p class="research-lead">${escapeText(report.businessDeck.deckSubtitle)}</p>` : ""}
    ${deckStatusMessage}
    ${renderBusinessDeckMeta(report.businessDeck)}
    <div class="research-delivery-strip">${actionButtons || '<span class="muted">No deck artifact buttons available yet.</span>'}</div>
    <div class="research-summary-grid">
      ${renderListSection("Generated At", report.businessDeck.generatedAt ? [formatDateTime(report.businessDeck.generatedAt)] : [], { emptyText: "Not generated yet." })}
      ${renderListSection("Deck Warnings", report.businessDeck.warnings, { emptyText: "No deck warnings recorded." })}
      ${report.businessDeck.preservationSummary ? renderListSection("Preservation Summary", [
        `Ranked conclusions used: ${report.businessDeck.preservationSummary.usedRankedConclusionCount}`,
        `Reverse conditions used: ${report.businessDeck.preservationSummary.usedReverseConditionCount}`,
        `Evidence gaps used: ${report.businessDeck.preservationSummary.usedEvidenceGapCount}`,
        `References used: ${report.businessDeck.preservationSummary.usedReferenceCount}`,
        `Omitted items: ${report.businessDeck.preservationSummary.omittedItemCount}`,
      ]) : ""}
    </div>
    <section class="research-copy-block">
      <h3>Slide Outline</h3>
      <div class="research-question-tree">
        ${report.businessDeck.slideSummaries.length
          ? report.businessDeck.slideSummaries.map((slide) => `
            <article class="research-question-card">
              <h4>#${escapeText(slide.slideNumber)} ${escapeText(slide.title)}</h4>
              <p>${escapeText(slide.headline)}</p>
              ${renderMetaRow([slide.slideType])}
            </article>`).join("")
          : '<p class="muted">No slide outline recorded.</p>'}
      </div>
    </section>`);
};

export const deepResearchClientDeliverySectionsRuntime = {
  renderPrimaryBusinessReport,
  renderBusinessDeckActions,
  renderBusinessDeckMeta,
  renderOptionalPresentationDeck,
} as const;