import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const protocolDirectory = dirname(fileURLToPath(import.meta.url));
const [protocol, errors, capabilities, protocolSource] = await Promise.all([
  JSON.parse(await readFile(join(protocolDirectory, "browser-protocol.schema.json"), "utf8")),
  JSON.parse(await readFile(join(protocolDirectory, "browser-errors.json"), "utf8")),
  JSON.parse(await readFile(join(protocolDirectory, "browser-capabilities.json"), "utf8")),
  readFile(join(protocolDirectory, "browser-protocol.schema.json")),
]);
const digest = createHash("sha256").update(protocolSource).digest("hex");
const output = `/** Generated by protocol/generate-browser-protocol.mjs. Do not edit. */
export const BROWSER_PROTOCOL_REVISION = ${protocol.revision} as const;
export const BROWSER_ARTIFACT_CHUNK_MAX_BYTES = ${protocol.transport.artifactChunkMaxBytes} as const;
export const BROWSER_COMMAND_MAX_IN_FLIGHT = ${protocol.commandAdmission.maxInFlightCommandsPerTarget} as const;
export const BROWSER_COMMAND_DEFAULT_DEADLINE_MS = ${protocol.commandAdmission.defaultDeadlineMs} as const;
export const BROWSER_TARGET_ACQUISITION_MAX_WAIT_MS = ${protocol.commandAdmission.targetAcquisitionMaxWaitMs} as const;
export const BROWSER_HEARTBEAT_MS = ${protocol.liveness.heartbeatMs} as const;
export const BROWSER_MISSED_HEARTBEAT_TOLERANCE_MS = ${protocol.liveness.missedHeartbeatToleranceMs} as const;
export const BROWSER_PROTOCOL_SCHEMA_SHA256 = "sha256:${digest}" as const;
export const BROWSER_ERROR_CODES = ${JSON.stringify(errors.codes)} as const;
export type BrowserErrorCode = (typeof BROWSER_ERROR_CODES)[number];
export const BROWSER_CAPABILITIES = ${JSON.stringify(capabilities.capabilities)} as const;
export type BrowserCapabilityId = (typeof BROWSER_CAPABILITIES)[number];
export const isBrowserCapabilityId = (value: string): value is BrowserCapabilityId => BROWSER_CAPABILITIES.includes(value as BrowserCapabilityId);
`;
const outputPath = join(protocolDirectory, "generated", "browser-protocol.generated.ts");
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");
